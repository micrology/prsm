import markdownToDelta from 'markdown-to-quill-delta'
import { alertMsg } from '../shared/utils.js'

const WARNING = 'This text has been generated by AI. It needs to be checked carefully.'

const FACTOR_PROMPT = `You are to explain a single factor, A.
Follow all the instructions below for your response:

Write a compact, clear explanation of what A is, what it measures and how it may vary.

Structure the output in the following order without using any section headings or a title:
1 Introduction
2 Bullet points explaining features of A.
3 Evidence section containing academic citations and links to relevant web pages
4 Summary
Always begin the answer with: > ***This text has been generated by AI. It needs to be checked carefully.***
Do not begin by repeating the factor that is being explained.
The introduction should be no more than 50 words.
The bullet points should clearly explain features of A in no more than 150 words.
The evidence section should provide academic references that support the explanation, with a brief explanation of how each reference supports it.
All academic references must include full citations (author, date, title, source). Do not include DOIs.  You must verify that all academic references that you mention actually exist.
Always embed links for any referenced web pages.
The summary should concisely restate the main points in no more than 50 words.

Maximum total output length: 200 words.
Format everything in Markdown.`

const LINK_PROMPT = `You are to explain a single causal link of the form A causes B.
Follow all the instructions below for your response:

Write a compact, clear explanation of why or how A causes B.
Do not introduce new factors that are not present in the inputs.
Do not restate or describe the whole system — focus only on the causal pathway from A to B, optionally referencing intermediary factors if necessary to provide a clear causal pathway.
Structure the output in the following order without using any section headings or a title:
1 Introduction
2 Bullet points explaining the causal reasoning
3 Evidence section containing academic citations and links to relevant web pages
4 Summary
Always begin the answer with: > ***This text has been generated by AI. It needs to be checked carefully.***
Do not begin by repeating the causal link that is being explained.
The introduction should be no more than 50 words.
The bullet points should clearly explain the causal reasoning in no more than 150 words.
The evidence section should provide academic references that support the causal link, with a brief explanation of how each reference supports the link.
All academic references must include full citations (author, date, title, source). Do not include DOIs.  You must verify that all academic references that you mention actually exist.
Always embed links for any referenced web pages.
The summary should concisely restate the main points in no more than 50 words.

Maximum total output length: 200 words.
Format everything in Markdown.`

/**
 * Request a Markdown response and convert it into a Quill delta.
 * @param {string} baseUrl Service origin.
 * @param {string} room Current room.
 * @param {string} message User prompt.
 * @param {string|null} [systemPrompt] Instructions for the model.
 * @returns {Promise<object>} Quill delta.
 */
export async function getAIresponse(baseUrl, room, message, systemPrompt = null) {
  const response = await fetch(`${baseUrl}/api/chat/${encodeURIComponent(room)}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ message, systemPrompt }),
  })
  let data
  try {
    data = await response.json()
  } catch (error) {
    if (!(error instanceof SyntaxError)) throw error
    const message = response.ok
      ? 'Invalid response from the AI service'
      : `HTTP ${response.status}${response.statusText ? ` ${response.statusText}` : ''}`
    throw new Error(message, { cause: error })
  }
  if (!response.ok || data?.error) throw new Error(data?.error || `HTTP ${response.status}`)
  if (typeof data?.response !== 'string' || !data.response.trim()) {
    throw new Error('Invalid response from the AI service')
  }
  const warningPrefix =
    /^\s*(?:>\s*)?[*_]*This text has been generated by AI\. It needs to be checked carefully\.[*_]*\s*/
  const text = data.response.replace(warningPrefix, '')
  return { ops: markdownToDelta(`> ***${WARNING}***\n\n${text}`) }
}

/**
 * Generate a factor or link note without overwriting subsequent edits.
 * @param {object} options Generation dependencies.
 * @returns {Promise<void>}
 */
export async function generateElementNote({
  store,
  kind,
  id,
  noteText,
  baseUrl,
  room,
  isReadOnly,
}) {
  if (isReadOnly()) throw new Error('This map is read-only')
  const record = store[kind].get(id)
  if (!record) throw new Error('The selected item no longer exists')
  const snapshot = JSON.stringify([
    record.note,
    record.created,
    record.label,
    record.source,
    record.target,
  ])
  let context = [...store.nodes.values()]
    .map((n) => (n.label ?? '').replaceAll('\n', ' '))
    .join(', ')
  const userPrompt = noteText.trim()
  if (!userPrompt.includes('This text has been generated by AI')) {
    context += `, and also consider: ${userPrompt}`
  }
  let message = `Explain ${record.label}. Use these keywords as context: ${context}`
  if (kind === 'edges') {
    const source = store.nodes.get(record.source)
    const target = store.nodes.get(record.target)
    if (!source || !target) throw new Error('The link factors no longer exist')
    message = `\nExplain the causal link from ${source.label} to ${target.label}. \nUse these keywords as context: ${context}`
  }
  const note = await getAIresponse(
    baseUrl,
    room,
    message,
    kind === 'nodes' ? FACTOR_PROMPT : LINK_PROMPT
  )
  const current = store[kind].get(id)
  if (
    isReadOnly() ||
    !current ||
    JSON.stringify([
      current.note,
      current.created,
      current.label,
      current.source,
      current.target,
    ]) !== snapshot
  ) {
    throw new Error('The note or map changed while AI was processing; the response was not saved')
  }
  store.update(kind, id, { note })
}

/**
 * Generate the map overview without overwriting subsequent edits.
 * @param {object} options Generation dependencies.
 * @returns {Promise<void>}
 */
export async function generateOverview({ store, baseUrl, room, isReadOnly }) {
  if (isReadOnly()) throw new Error('This map is read-only')
  if (!store.nodes.size) throw new Error('Add some factors and causal links to the map first')
  const original = JSON.stringify(store.meta.get('description')?.text)
  const causes = [...store.edges.values()]
    .map((edge) => {
      const source = store.nodes.get(edge.source)
      const target = store.nodes.get(edge.target)
      if (!source || !target) throw new Error('A link has a missing factor')
      return `${(source.label ?? '').replaceAll('\n', ' ')} causes ${(target.label ?? '').replaceAll('\n', ' ')}`
    })
    .join('; ')
  const title = store.meta.get('title')?.trim() || 'System Map'
  const note = await getAIresponse(
    baseUrl,
    room,
    `I want you to generate a compact, readable narrative description of a system map.

I will provide:
• A title for the system map.
• A list of causal links, each given as a pair of factors in the form “A causes B”, where A is the cause and B is the effect.

Your task is to:
	1.	Produce a short, coherent, well-structured markdown description explaining the main dynamics of the system.
	2.	Cluster related factors, highlight feedback loops if present, and describe the overall behaviour of the system.
	3.	Avoid restating every causal link individually. Instead, synthesise them into a readable explanation.
	4.	Use bullet points where appropriate but do *not* include a title or any section headings.
	5.	Keep the description concise and accessible, suitable for a briefing note.  Use no more than 300 words.
  
Output only the final description in markdown.

Here is the title and list of causal links:
Title: >>>${title}<<<
Causal Links:
 >>>${causes}<<<`
  )
  if (isReadOnly() || JSON.stringify(store.meta.get('description')?.text) !== original) {
    throw new Error(
      'The overview or map changed while AI was processing; the response was not saved'
    )
  }
  store.transact(() =>
    store.meta.set('description', { ...store.meta.get('description'), text: note })
  )
}

/**
 * Show progress and report failures without replacing the existing note.
 * @param {HTMLButtonElement} button Generation control.
 * @param {function():Promise<void>} generate Generation operation.
 * @returns {Promise<void>}
 */
export async function runAI(button, generate) {
  if (button.disabled) return
  button.disabled = true
  button.classList.add('rotating')
  button.setAttribute('aria-busy', 'true')
  try {
    await generate()
  } catch (error) {
    console.error('AI note generation failed:', error)
    const message = String(error.message)
      .replaceAll('&', '&amp;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;')
    alertMsg(`AI: ${message}`, 'error')
  } finally {
    button.disabled = false
    button.classList.remove('rotating')
    button.removeAttribute('aria-busy')
  }
}
