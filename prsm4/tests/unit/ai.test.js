import { test } from 'node:test'
import assert from 'node:assert/strict'
import { MapStore } from '../../src/graph/store.js'

globalThis.window = {}
const { getAIresponse, generateElementNote, generateOverview } = await import('../../src/app/ai.js')

/** Create a small map for note generation. */
function makeStore() {
  const store = new MapStore()
  store.loadFile({
    meta: { title: 'A map', description: { text: { ops: [{ insert: 'Original overview\n' }] } } },
    nodes: [
      { id: 'a', label: 'Apple', note: { ops: [{ insert: 'Consider fruit\n' }] } },
      { id: 'b', label: 'Orange' },
    ],
    edges: [{ id: 'e', source: 'a', target: 'b' }],
    styles: {},
  })
  return store
}

const params = {
  baseUrl: 'http://localhost:4174',
  room: 'ABC-DEF-GHI-JKL',
  isReadOnly: () => false,
}

test('AI requests encode the room, preserve prompts, and ensure a single warning', async (t) => {
  const fetch = t.mock.method(globalThis, 'fetch', async () =>
    Response.json({
      response:
        '> ***This text has been generated by AI. It needs to be checked carefully.***\n\nAnswer',
    })
  )
  const delta = await getAIresponse(params.baseUrl, 'room/name', 'Question', 'Instructions')
  const [url, options] = fetch.mock.calls[0].arguments
  assert.equal(url, 'http://localhost:4174/api/chat/room%2Fname')
  assert.deepEqual(JSON.parse(options.body), { message: 'Question', systemPrompt: 'Instructions' })
  const text = delta.ops.map((op) => op.insert).join('')
  assert.equal(text.match(/This text has been generated by AI/g).length, 1)
  assert.match(text, /^This text has been generated by AI\. It needs to be checked carefully\./)
  fetch.mock.mockImplementation(async () => Response.json({ response: 'Answer' }))
  const missing = await getAIresponse(params.baseUrl, params.room, 'Question')
  assert.match(missing.ops[0].insert, /^This text has been generated by AI/)
  fetch.mock.mockImplementation(async () =>
    Response.json({ error: 'Unavailable' }, { status: 503 })
  )
  await assert.rejects(getAIresponse(params.baseUrl, params.room, 'Question'), /Unavailable/)
  fetch.mock.mockImplementation(async () => Response.json({ response: '' }))
  await assert.rejects(getAIresponse(params.baseUrl, params.room, 'Question'), /Invalid response/)
  fetch.mock.mockImplementation(
    async () => new Response(null, { status: 405, statusText: 'Method Not Allowed' })
  )
  await assert.rejects(
    getAIresponse(params.baseUrl, params.room, 'Question'),
    /HTTP 405 Method Not Allowed/
  )
  fetch.mock.mockImplementation(async () => new Response('Not JSON', { status: 502 }))
  await assert.rejects(getAIresponse(params.baseUrl, params.room, 'Question'), /HTTP 502/)
  fetch.mock.mockImplementation(async () => new Response(''))
  await assert.rejects(getAIresponse(params.baseUrl, params.room, 'Question'), /Invalid response/)
  fetch.mock.mockImplementation(async () => Response.json(null))
  await assert.rejects(getAIresponse(params.baseUrl, params.room, 'Question'), /Invalid response/)
})

test('factor and link generation use the legacy context and write to the requested record', async (t) => {
  const store = makeStore()
  t.after(() => store.doc.destroy())
  const fetch = t.mock.method(globalThis, 'fetch', async () =>
    Response.json({ response: 'Generated' })
  )
  await generateElementNote({
    ...params,
    store,
    kind: 'nodes',
    id: 'a',
    noteText: 'Consider fruit',
  })
  let body = JSON.parse(fetch.mock.calls[0].arguments[1].body)
  assert.match(body.message, /Explain Apple.*Apple, Orange, and also consider: Consider fruit/)
  assert.match(body.systemPrompt, /explain a single factor/)
  assert.match(store.nodes.get('a').note.ops[0].insert, /^This text has been generated/)
  await generateElementNote({
    ...params,
    store,
    kind: 'edges',
    id: 'e',
    noteText: 'This text has been generated by AI',
  })
  body = JSON.parse(fetch.mock.calls[1].arguments[1].body)
  assert.match(body.message, /causal link from Apple to Orange/)
  assert.doesNotMatch(body.message, /also consider/)
  assert.match(body.systemPrompt, /single causal link/)
  assert.match(store.edges.get('e').note.ops[0].insert, /^This text has been generated/)
})

test('overview generation sends map title and links and preserves other description fields', async (t) => {
  const store = makeStore()
  t.after(() => store.doc.destroy())
  const fetch = t.mock.method(globalThis, 'fetch', async () =>
    Response.json({ response: 'Overview' })
  )
  await generateOverview({ ...params, store })
  const body = JSON.parse(fetch.mock.calls[0].arguments[1].body)
  assert.match(body.message, /Title: >>>A map<<</)
  assert.match(body.message, /Apple causes Orange/)
  assert.equal(body.systemPrompt, null)
  assert.match(store.meta.get('description').text.ops[0].insert, /^This text has been generated/)
})

test('pending requests do not overwrite edited, deleted or read-only targets', async (t) => {
  const store = makeStore()
  t.after(() => store.doc.destroy())
  let respond
  t.mock.method(
    globalThis,
    'fetch',
    () =>
      new Promise((resolve) => {
        respond = resolve
      })
  )
  const start = () =>
    generateElementNote({ ...params, store, kind: 'nodes', id: 'a', noteText: '' })
  let pending = start()
  store.update('nodes', 'a', { note: { ops: [{ insert: 'New note\n' }] } })
  respond(Response.json({ response: 'Old AI answer' }))
  await assert.rejects(pending, /not saved/)
  assert.equal(store.nodes.get('a').note.ops[0].insert, 'New note\n')
  pending = start()
  store.remove(['a'])
  respond(Response.json({ response: 'Old AI answer' }))
  await assert.rejects(pending, /not saved/)
  pending = generateOverview({
    ...params,
    store,
    isReadOnly: () => Boolean(store.meta.get('viewOnly')),
  })
  store.meta.set('viewOnly', true)
  respond(Response.json({ response: 'Old AI answer' }))
  await assert.rejects(pending, /not saved/)
  assert.equal(store.meta.get('description').text.ops[0].insert, 'Original overview\n')
})

test('overview changes and failed requests leave existing notes untouched', async (t) => {
  const store = makeStore()
  t.after(() => store.doc.destroy())
  let respond
  const fetch = t.mock.method(
    globalThis,
    'fetch',
    () =>
      new Promise((resolve) => {
        respond = resolve
      })
  )
  const pending = generateOverview({ ...params, store })
  store.meta.set('description', { text: { ops: [{ insert: 'New overview\n' }] } })
  respond(Response.json({ response: 'Old AI answer' }))
  await assert.rejects(pending, /not saved/)
  assert.equal(store.meta.get('description').text.ops[0].insert, 'New overview\n')
  fetch.mock.mockImplementation(async () =>
    Response.json({ error: 'Unavailable' }, { status: 503 })
  )
  await assert.rejects(
    generateElementNote({ ...params, store, kind: 'nodes', id: 'a', noteText: '' }),
    /Unavailable/
  )
  assert.equal(store.nodes.get('a').note.ops[0].insert, 'Consider fruit\n')
})
